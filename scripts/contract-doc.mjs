#!/usr/bin/env node
// Generates docs/token-contract.md from tokens.css + scripts/contract.json. Deterministic (no dates), so re-running it on
// unchanged inputs yields a byte-identical file. 用途 comes ONLY from comments in tokens.css (nearest comment inside the
// rule block, else the section comment right above the block); nothing found -> 「待补」.
// Usage: npm run contract-doc            (writes docs/token-contract.md)
//        npm run contract-doc -- --check (exit 1 if the file is missing or stale; writes nothing)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { loadContract, pairsOf } from "./lib/tokens.mjs";
const dir = new URL("../", import.meta.url);
const src = readFileSync(new URL("tokens.css", dir), "utf8");
const contract = loadContract(dir);
const P = pairsOf(contract);
const LABEL = { ":root": "light (:root)", ':root[data-theme="light"]': "light", ':root[data-theme="dark"]': "dark", ".band-sea--night": ".band-sea--night", ".band-sea--dawn": ".band-sea--dawn" };
const clean = (c) => c.replace(/^\/\*+|\*+\/$/g, "").replace(/-{3,}/g, "").replace(/\s+/g, " ").trim();
const esc = (s) => s.replace(/\|/g, "\\|");

// walk the file: comments, @property blocks and rule blocks in source order
const rows = new Map(); // token -> { scopes: [[label, value]], use }
let lastComment = null;
const re = /\/\*[\s\S]*?\*\/|@property\s+--[\w-]+\s*\{[^{}]*\}|([^{}\s/][^{}]*?)\{([^{}]*)\}/g;
for (const m of src.matchAll(re)) {
  if (m[0].startsWith("/*")) { lastComment = clean(m[0]); continue; }
  if (m[0].startsWith("@property")) continue;
  const sels = m[1].replace(/\/\*[\s\S]*?\*\//g, "").split(",").map((s) => s.trim()).filter(Boolean);
  const blockComment = lastComment; lastComment = null;
  let inner = blockComment;
  for (const part of m[2].split(/(\/\*[\s\S]*?\*\/)/)) {
    if (part.startsWith("/*")) { inner = clean(part); continue; }
    for (const d of part.split(";")) {
      const i = d.indexOf(":"); if (i <= 0) continue; const k = d.slice(0, i).trim(); if (!k.startsWith("--")) continue;
      const v = d.slice(i + 1).trim().replace(/\s+/g, " ");
      if (!rows.has(k)) rows.set(k, { scopes: [], uses: [] });
      const r = rows.get(k);
      for (const s of sels) r.scopes.push([LABEL[s] ?? s, v]);
      if (inner && !r.uses.includes(inner)) r.uses.push(inner);
    }
  }
}
const pairsFor = (k) => P.filter(([, fg, bg]) => "--" + fg === k || "--" + bg === k).map(([m, fg, bg, min]) => `${m}: ${fg} on ${bg} ≥ ${min}`);
const out = [];
out.push("# Token contract / 令牌目录");
out.push("");
out.push("> 由 `npm run contract-doc` 从 `tokens.css` + `scripts/contract.json` 生成，请勿手改。用途列只摘 `tokens.css` 注释原文，查不到写「待补」。");
out.push("> Generated by `npm run contract-doc`; do not edit by hand.");
out.push("");
out.push(`共 ${rows.size} 个自定义属性；对比度对 ${P.length} 对登记在 scripts/contract.json（疾病色 --d-* 另有固定规则，见 check.mjs）。`);
out.push("");
out.push("| token | 作用域: 取值 | 用途（tokens.css 注释） | 对比度检查 | 消费方局部覆盖 |");
out.push("|---|---|---|---|---|");
for (const [k, r] of rows) {
  const scopes = r.scopes.map(([s, v]) => `${esc(s)}: \`${esc(v.length > 60 ? v.slice(0, 57) + "…" : v)}\``).join("<br>");
  const pc = k.startsWith("--d-") ? "疾病色规则 ×5" : pairsFor(k).join("<br>") || "—";
  const ov = contract.consumerOverride?.[k] ? esc(contract.consumerOverride[k]) : "待补";
  out.push(`| \`${k}\` | ${scopes} | ${esc(r.uses.join("；")) || "待补"} | ${pc} | ${ov} |`);
}
const text = out.join("\n") + "\n";
const target = new URL("docs/token-contract.md", dir);
if (process.argv.includes("--check")) {
  let cur = null; try { cur = readFileSync(target, "utf8"); } catch {}
  if (cur !== text) { console.log("docs/token-contract.md is stale (run npm run contract-doc)"); process.exit(1); }
  console.log(`ok: docs/token-contract.md up to date (${rows.size} tokens)`);
} else {
  mkdirSync(new URL("docs/", dir), { recursive: true }); writeFileSync(target, text); console.log(`wrote docs/token-contract.md (${rows.size} tokens)`);
}
